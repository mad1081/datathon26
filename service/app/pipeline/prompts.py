def taxonomy_block(rb: RuleBook) -> str:
    lines = []
    for r in rb.rules.values():
        lines.append(f'- "{r.id}": {r.name_ru}. Признаки: {r.visual_criteria} ({r.vlm_hint}). '
                     f'НЕ является нарушением/не утверждать: {r.negatives}'
                     + (f' Пример из размеченных видео: {FEWSHOT[r.id]}' if r.id in FEWSHOT else ''))
    return "\n".join(lines)


def window_system(rb: RuleBook) -> str:
    """Static part (system) — identical for every window, so local servers can prefix-cache it."""
    states = "; ".join(f'"{k}" — {v}' for k, v in STATES_RU.items())
    return (
        SYSTEM + "\n\nТипы возможных нарушений:\n" + taxonomy_block(rb) + "\n\n"
        "Задача: по последовательным кадрам определи, есть ли визуальные признаки какого-либо нарушения из списка. "
        "Учитывай динамику между кадрами (кто вошёл/вышел, что осталось на столе, открыта ли дверь/сейф, "
        "торчит ли ключ, заблокирован ли экран ноутбука, предъявлен ли документ). "
        "Ракурс, где камера за спиной кассира и клиенты штатно сидят рядом с ним, — нормальная планировка.\n"
        + NOT_VIOLATION_EXAMPLES + "\n"
        "Также отметь состояния сцены в этом окне (true, если состояние видно хотя бы на части кадров): "
        + states + ".\n"
        "Верни JSON строго такого вида:\n"
        '{"scene": "<1 фраза по-русски: что происходит>", '
        '"events": [{"type": "<id из списка>", "confidence": <0..1>, "start_sec": <число>, '
        '"end_sec": <число>, "peak_sec": <момент, когда нарушение впервые явно видно>, '
        '"evidence": "<по-русски: что конкретно видно на кадрах>"}], '
        '"states": {"client_at_window": true|false, "cashier_at_desk": true|false, "cash_in_hands": true|false, '
        '"counting": true|false, "second_employee": true|false, "phone": true|false}}\n'
        'Если нарушений нет — "events": []. Используй только id из списка; время — в секундах видео.'
    )


def window_prompt(rb: RuleBook, t0: float, t1: float, timestamps: list[float]) -> str:
    ts = ", ".join(f"{t:.1f}" for t in timestamps)
    return (f"Выше — кадры видео с {t0:.1f} по {t1:.1f} с (метки времени: {ts}). "
            "Проанализируй их по инструкции и верни только JSON.")


def verify_prompt(rb: RuleBook, rule_id: str, t: float) -> str:
    r = rb.get(rule_id)
    return (
        f"Кадр видео на {t:.2f} с (и, если даны, соседние кадры для контекста). "
        f"Проверь один признак: «{r.name_ru}». Признаки: {r.visual_criteria} ({r.vlm_hint}). "
        f"Не является нарушением: {r.negatives}\n"
        'Верни JSON: {"visible": true|false, "confidence": <0..1>, "evidence": "<по-русски, кратко>"}'
    )
